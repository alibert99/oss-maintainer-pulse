def _markdown_queue(
    title: str,
    items: list[WorkItem],
    now: datetime,
    *,
    limit: int,
) -> list[str]:
    lines = [f"## {title}", ""]
    if not items:
        lines.extend(["No items in this queue.", ""])
        return lines

    lines.extend(_markdown_items_table(items[:limit], now))
    lines.append("")
    return lines


def _markdown_release_blockers(
    items: list[WorkItem],
    now: datetime,
    *,
    limit: int,
) -> list[str]:
    lines = ["## Release Blockers", ""]
    if not items:
        lines.extend(["No items in this queue.", ""])
        return lines

    grouped: dict[str, list[WorkItem]] = {}
    for item in items[:limit]:
        grouped.setdefault(item.milestone_title or "No milestone", []).append(item)

    for milestone in sorted(grouped, key=lambda name: (name == "No milestone", name.lower())):
        lines.extend([f"### {escape_markdown(milestone)}", ""])
        lines.extend(_markdown_items_table(grouped[milestone], now))
        lines.append("")
    return lines


def _markdown_items_table(items: list[WorkItem], now: datetime) -> list[str]:
    lines = ["| Item | Labels | Idle | Age |", "| --- | --- | ---: | ---: |"]
    for item in items:
        item_link = f"[#{item.number} {escape_markdown(item.title)}]({item.html_url})"
        labels = ", ".join(item.labels) if item.labels else "-"
        lines.append(
            f"| {item_link} | {escape_markdown(labels)} | {idle_days(item, now)}d | "
            f"{age_days(item, now)}d |"
        )
    return lines


def _markdown_duplicate_candidates(
    candidates: list[DuplicateCandidate],
    *,
    limit: int,
) -> list[str]:
    lines = ["## Duplicate Candidates", ""]
    if not candidates:
        lines.extend(["No likely duplicate candidates found.", ""])
        return lines

    lines.extend(
        [
            "| Items | Similarity | Shared terms |",
            "| --- | ---: | --- |",
        ]
    )
    for candidate in candidates[:limit]:
        first = candidate.first
        second = candidate.second
        first_link = f"[#{first.number} {escape_markdown(first.title)}]({first.html_url})"
        second_link = f"[#{second.number} {escape_markdown(second.title)}]({second.html_url})"
        shared = ", ".join(candidate.shared_terms)
        lines.append(
            f"| {first_link}<br>{second_link} | {candidate.similarity:.2f} | "
            f"{escape_markdown(shared)} |"
        )
    lines.append("")
    return lines


def report_to_dict(report: PulseReport, *, limit: int) -> dict[str, Any]:
    return {
        "repository": report.repository,
        "generated_at": report.generated_at.isoformat(timespec="seconds"),
        "stale_days": report.stale_days,
        "metrics": report.metrics.__dict__,
        "ai_summary": (
            {
                "provider": report.ai_provider or "",
                "model": report.ai_model or "",
                "text": report.ai_summary,
            }
            if report.ai_summary
            else None
        ),
        "duplicate_candidates": [
            _duplicate_candidate_to_dict(candidate) for candidate in report.duplicate_candidates[:limit]
        ],
        "recommendations": report.recommendations,
        "queues": {
            name: [_item_to_dict(item, report.generated_at) for item in items[:limit]]
            for name, items in report.queues.items()
        },
    }


def _duplicate_candidate_to_dict(candidate: DuplicateCandidate) -> dict[str, Any]:
    return {
        "first": _item_summary(candidate.first),
        "second": _item_summary(candidate.second),
        "similarity": candidate.similarity,
        "shared_terms": list(candidate.shared_terms),
    }


def _item_summary(item: WorkItem) -> dict[str, Any]:
    return {
        "number": item.number,
        "title": item.title,
        "html_url": item.html_url,
        "labels": list(item.labels),
    }


def _item_to_dict(item: WorkItem, now: datetime) -> dict[str, Any]:
    return {
        "number": item.number,
        "title": item.title,
        "state": item.state,
        "labels": list(item.labels),
        "author": item.author,
        "html_url": item.html_url,
        "milestone_title": item.milestone_title,
        "created_at": item.created_at.isoformat(timespec="seconds"),
        "updated_at": item.updated_at.isoformat(timespec="seconds"),
        "closed_at": item.closed_at.isoformat(timespec="seconds") if item.closed_at else None,
        "comments": item.comments,
        "is_pull_request": item.is_pull_request,
        "idle_days": idle_days(item, now),
        "age_days": age_days(item, now),
    }


def _csv_item(queue_name: str, item: WorkItem, now: datetime) -> dict[str, Any]:
    return {
        "queue": queue_name,
        "number": item.number,
        "title": item.title,
        "type": "pull_request" if item.is_pull_request else "issue",
        "state": item.state,
        "labels": "; ".join(item.labels),
        "milestone": item.milestone_title or "",
        "author": item.author,
        "comments": item.comments,
        "idle_days": idle_days(item, now),
        "age_days": age_days(item, now),
        "created_at": item.created_at.isoformat(timespec="seconds"),
        "updated_at": item.updated_at.isoformat(timespec="seconds"),
        "closed_at": item.closed_at.isoformat(timespec="seconds") if item.closed_at else "",
        "url": item.html_url,
    }


def _html_item(item: dict[str, Any]) -> str:
    labels = "".join(f"<span class=\"label\">{html.escape(label)}</span>" for label in item["labels"])
    url = html.escape(item["html_url"])
    title = html.escape(item["title"])
    details = [
        f"{item['idle_days']} idle days",
        f"{item['age_days']} days old",
        f"{item['comments']} comments",
    ]
    if item["milestone_title"]:
        details.append(f"milestone: {html.escape(item['milestone_title'])}")
    return f"""<article class="item">
  <a href="{url}">#{item["number"]} {title}</a>
  <p>{' · '.join(details)}</p>
  <div class="labels">{labels}</div>
</article>"""


def _html_duplicate(candidate: dict[str, Any]) -> str:
    first = candidate["first"]
    second = candidate["second"]
    shared = ", ".join(candidate["shared_terms"]) or "-"
    return f"""<article class="item">
  <a href="{html.escape(first["html_url"])}">#{first["number"]} {html.escape(first["title"])}</a>
  <p>Likely duplicate of <a href="{html.escape(second["html_url"])}">#{second["number"]} {html.escape(second["title"])}</a></p>
  <p>Similarity: {candidate["similarity"]:.2f} - Shared terms: {html.escape(shared)}</p>
</article>"""


def _html_markdownish(value: str) -> str:
    paragraphs = [paragraph.strip() for paragraph in value.split("\n\n") if paragraph.strip()]
    return "".join(f"<p>{html.escape(paragraph)}</p>" for paragraph in paragraphs)


def escape_markdown(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ")


def _display_optional(value: float | None) -> str:
    return "-" if value is None else str(value)
