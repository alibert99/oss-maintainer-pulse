def render_markdown(report: PulseReport, *, limit: int = 10) -> str:
    metrics = report.metrics
    lines = [
        f"# Maintainer Pulse: {report.repository}",
        "",
        f"Generated: {report.generated_at.isoformat(timespec='seconds')}",
        "",
        "## Health Snapshot",
        "",
        "| Metric | Value |",
        "| --- | ---: |",
        f"| Health score | {metrics.health_score}/100 |",
        f"| Open issues | {metrics.open_issues} |",
        f"| Open pull requests | {metrics.open_pull_requests} |",
        f"| Release blockers | {metrics.release_blockers} |",
        f"| Stuck pull requests | {metrics.stuck_pull_requests} |",
        f"| Response debt | {metrics.response_debt} |",
        f"| Stale items ({report.stale_days}+ idle days) | {metrics.stale_items} |",
        f"| Closed in last 90 days | {metrics.recent_closed} |",
        f"| Median days to close | {_display_optional(metrics.median_days_to_close)} |",
        "",
        "## Recommended Maintainer Block",
        "",
    ]
    lines.extend(f"- {recommendation}" for recommendation in report.recommendations)
    lines.append("")

    if report.ai_summary:
        lines.extend(
            [
                "## AI Maintainer Summary",
                "",
                f"Provider: {report.ai_provider or 'unknown'}",
                f"Model: {report.ai_model or 'unknown'}",
                "",
                "AI-generated guidance is advisory. Verify repository context before acting.",
                "",
                report.ai_summary.strip(),
                "",
            ]
        )

    for title, key in (
        ("Release Blockers", "release_blockers"),
        ("Stuck Pull Requests", "stuck_pull_requests"),
        ("Needs First Response", "response_debt"),
        ("Stale Queue", "stale_items"),
        ("Quick Wins", "quick_wins"),
    ):
        if key == "release_blockers":
            lines.extend(_markdown_release_blockers(report.queues[key], report.generated_at, limit=limit))
        else:
            lines.extend(_markdown_queue(title, report.queues[key], report.generated_at, limit=limit))

    lines.extend(_markdown_duplicate_candidates(report.duplicate_candidates, limit=limit))

    lines.extend(
        [
            "---",
            "",
            "Generated by Maintainer Pulse. Verify labels and context before making release decisions.",
            "",
        ]
    )
    return "\n".join(lines)


def render_json(report: PulseReport, *, limit: int = 25) -> str:
    return json.dumps(report_to_dict(report, limit=limit), indent=2, sort_keys=True)


def render_csv(report: PulseReport, *, limit: int = 25) -> str:
    output = io.StringIO()
    writer = csv.DictWriter(
        output,
        fieldnames=[
            "queue",
            "number",
            "title",
            "type",
            "state",
            "labels",
            "milestone",
            "author",
            "comments",
            "idle_days",
            "age_days",
            "created_at",
            "updated_at",
            "closed_at",
            "url",
        ],
    )
    writer.writeheader()
    for queue_name, items in report.queues.items():
        for item in items[:limit]:
            writer.writerow(_csv_item(queue_name, item, report.generated_at))
    return output.getvalue()


